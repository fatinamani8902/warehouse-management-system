BEGIN;

-- Only legacy codes are repaired. Valid generated codes such as 001, 002, and
-- 1000 are left unchanged.
CREATE TEMP TABLE legacy_bay_code_repair ON COMMIT DROP AS
WITH legacy AS (
  SELECT
    b.tenant_id,
    b.aisle_id,
    b.bay_id,
    row_number() OVER (
      PARTITION BY b.tenant_id, b.aisle_id
      ORDER BY b.created_at, b.bay_id
    ) AS legacy_rank
  FROM public.warehouse_bays b
  WHERE b.bay_code !~ '^[0-9]{3,}$'
),
available_codes AS (
  SELECT
    parent.tenant_id,
    parent.aisle_id,
    candidate.code_number,
    row_number() OVER (
      PARTITION BY parent.tenant_id, parent.aisle_id
      ORDER BY candidate.code_number
    ) AS available_rank
  FROM (
    SELECT DISTINCT tenant_id, aisle_id
    FROM legacy
  ) parent
  CROSS JOIN LATERAL generate_series(
    1,
    (
      SELECT count(*)::integer + 1000
      FROM public.warehouse_bays counted
      WHERE counted.tenant_id = parent.tenant_id
        AND counted.aisle_id = parent.aisle_id
    )
  ) candidate(code_number)
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.warehouse_bays existing
    WHERE existing.tenant_id = parent.tenant_id
      AND existing.aisle_id = parent.aisle_id
      AND existing.bay_code ~ '^[0-9]{3,}$'
      AND existing.bay_code::bigint = candidate.code_number
  )
)
SELECT
  legacy.tenant_id,
  legacy.aisle_id,
  legacy.bay_id,
  lpad(available_codes.code_number::text, 3, '0') AS repaired_bay_code
FROM legacy
JOIN available_codes
  ON available_codes.tenant_id = legacy.tenant_id
 AND available_codes.aisle_id = legacy.aisle_id
 AND available_codes.available_rank = legacy.legacy_rank;

-- Move affected rows to collision-proof temporary values before assigning the
-- final per-aisle sequence. bay_name is intentionally not modified.
UPDATE public.warehouse_bays b
SET bay_code = '__LEGACY__' || b.bay_id,
    updated_at = now()
FROM legacy_bay_code_repair repair
WHERE b.tenant_id = repair.tenant_id
  AND b.aisle_id = repair.aisle_id
  AND b.bay_id = repair.bay_id;

UPDATE public.warehouse_bays b
SET bay_code = repair.repaired_bay_code,
    updated_at = now()
FROM legacy_bay_code_repair repair
WHERE b.tenant_id = repair.tenant_id
  AND b.aisle_id = repair.aisle_id
  AND b.bay_id = repair.bay_id;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.warehouse_bays
    WHERE bay_code !~ '^[0-9]{3,}$'
  ) THEN
    RAISE EXCEPTION 'Legacy Bay backfill failed: invalid bay_code remains';
  END IF;

  IF EXISTS (
    SELECT tenant_id, aisle_id, bay_code
    FROM public.warehouse_bays
    GROUP BY tenant_id, aisle_id, bay_code
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Legacy Bay backfill failed: duplicate bay_code detected within an aisle';
  END IF;
END $$;

COMMIT;

-- Migration verification query:
-- - bay_code must be a generated numeric code.
-- - bay_name remains unchanged.
-- - location_code is regenerated by the same hierarchy convention used by
--   the taxonomy API; it is derived, not stored in warehouse_bays.
SELECT
  b.tenant_id,
  b.bay_id,
  b.bay_code,
  b.bay_name,
  b.aisle_id,
  a.aisle_code,
  z.zone_code,
  w.warehouse_code,
  concat_ws('-', w.warehouse_code, z.zone_code, a.aisle_code, b.bay_code) AS location_code,
  (b.bay_code ~ '^[0-9]{3,}$') AS bay_code_valid
FROM public.warehouse_bays b
JOIN public.warehouse_aisles a
  ON a.tenant_id = b.tenant_id
 AND a.aisle_id = b.aisle_id
JOIN public.warehouse_zones z
  ON z.tenant_id = a.tenant_id
 AND z.zone_id = a.zone_id
JOIN public.warehouses w
  ON w.tenant_id = z.tenant_id
 AND w.warehouse_id = z.warehouse_id
ORDER BY b.tenant_id, b.aisle_id, b.bay_code;
